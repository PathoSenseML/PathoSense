"""F2: Per-panel ablation of tracks E1 (Platt), E2 (score-agreement), E3 (interactions).

Runs 5 configurations × 4 panels = 20 runs:
  - baseline (D6)            : no Platt, no score-agree, no interactions
  - +E1 only                 : Platt only
  - +E2 only                 : score-agreement only
  - +E3 only                 : interactions only
  - +all (E1+E2+E3)          : everything on

Captures per-config-per-panel calibrated balanced F1 (or balanced F1 if Platt
disabled) and writes to analysis/output/ablation.csv + ablation.md. The runner
suppresses verbose per-panel output; each cell is one number.

Run: python analysis/ablate.py
"""
import os
import sys
import io
import json
import time
import contextlib

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "pipelines"))
from run_pipeline import run_panel

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "output")
os.makedirs(OUT_DIR, exist_ok=True)

PANELS_TO_RUN = ["general", "cancer", "pah", "cftr"]
CONFIGS = [
    ("baseline",   dict(use_platt=False, use_score_agree=False, use_interactions=False)),
    ("E1_only",    dict(use_platt=True,  use_score_agree=False, use_interactions=False)),
    ("E2_only",    dict(use_platt=False, use_score_agree=True,  use_interactions=False)),
    ("E3_only",    dict(use_platt=False, use_score_agree=False, use_interactions=True)),
    ("all_on",     dict(use_platt=True,  use_score_agree=True,  use_interactions=True)),
]


def extract_deployed_f1(results):
    """Pick the F1 reported as 'deployed' by run_panel for this config.

    With Platt: f1_calibrated_value (calibrated + balanced).
    Without:    f1_balanced_value   (raw + balanced).
    """
    thr = results.get("threshold", {})
    flags = results.get("ablation_flags", {})
    if flags.get("use_platt", False):
        return thr.get("f1_calibrated_value", float("nan"))
    return thr.get("f1_balanced_value", float("nan"))


def run_one(panel, label, kwargs):
    print(f"  [{label:>9}] {panel} ...", end="", flush=True)
    t0 = time.time()
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        results = run_panel(panel, **kwargs)
    elapsed = time.time() - t0
    f1 = extract_deployed_f1(results)
    auc = results.get("oof_metrics", {}).get("auc", float("nan"))
    bal_raw = results.get("threshold", {}).get("f1_balanced_value", float("nan"))
    ece_cal = results.get("calibration", {}).get("ece_calibrated", float("nan"))
    print(f"  F1={f1:.4f}  AUC={auc:.4f}  ({elapsed:.0f}s)")
    return {
        "panel":   panel,
        "config":  label,
        "f1_deployed": round(f1, 4),
        "f1_balanced_raw": round(bal_raw, 4) if bal_raw == bal_raw else float("nan"),
        "oof_auc": round(auc, 4),
        "ece_cal": round(ece_cal, 4) if ece_cal == ece_cal else float("nan"),
        "elapsed_s": round(elapsed, 1),
        **kwargs,
    }


def main():
    print(f"Running {len(CONFIGS)} configs × {len(PANELS_TO_RUN)} panels = "
          f"{len(CONFIGS) * len(PANELS_TO_RUN)} runs total.\n")
    rows = []
    t_all = time.time()
    for label, cfg in CONFIGS:
        print(f"\n--- config: {label}  {cfg} ---")
        for panel in PANELS_TO_RUN:
            rows.append(run_one(panel, label, cfg))
    print(f"\nTotal elapsed: {time.time()-t_all:.0f}s")

    df = pd.DataFrame(rows)
    csv_path = os.path.join(OUT_DIR, "ablation.csv")
    df.to_csv(csv_path, index=False)
    print(f"\nwrote {csv_path}")

    # Pivot for readable markdown table
    pivot = df.pivot(index="config", columns="panel", values="f1_deployed")
    # Order rows by CONFIGS spec
    pivot = pivot.reindex([c[0] for c in CONFIGS])
    pivot["avg"] = pivot.mean(axis=1).round(4)
    pivot = pivot[PANELS_TO_RUN + ["avg"]]

    # Pick best config per panel
    best_per_panel = {}
    for p in PANELS_TO_RUN:
        sub = df[df["panel"] == p].copy()
        best = sub.loc[sub["f1_deployed"].idxmax()]
        best_per_panel[p] = {
            "config": best["config"],
            "f1":     float(best["f1_deployed"]),
            "auc":    float(best["oof_auc"]),
        }

    # Markdown summary
    lines = []
    lines.append("# Ablation Results\n")
    lines.append(f"Generated by `analysis/ablate.py` on {time.strftime('%Y-%m-%d %H:%M')}.\n")
    lines.append("Numbers are **calibrated balanced F1** (or balanced F1 when Platt is off). "
                 "This is the honest estimate at the 50/50 test prior the rules guarantee.\n")
    lines.append("## F1 by config × panel\n")
    lines.append("| Config | " + " | ".join(PANELS_TO_RUN + ["avg"]) + " |")
    lines.append("|" + "---|" * (len(PANELS_TO_RUN) + 2))
    for cfg in pivot.index:
        row = [cfg]
        for col in PANELS_TO_RUN + ["avg"]:
            v = pivot.loc[cfg, col]
            row.append(f"{v:.4f}" if v == v else "—")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")

    lines.append("## Best per-panel config\n")
    lines.append("| Panel | Best config | F1 | OOF AUC |")
    lines.append("|---|---|---|---|")
    for p in PANELS_TO_RUN:
        b = best_per_panel[p]
        lines.append(f"| {p} | **{b['config']}** | {b['f1']:.4f} | {b['auc']:.4f} |")
    lines.append("")

    # Delta vs baseline per (config, panel)
    lines.append("## Delta vs baseline (positive = config wins)\n")
    base = pivot.loc["baseline"]
    lines.append("| Config | " + " | ".join(PANELS_TO_RUN) + " |")
    lines.append("|" + "---|" * (len(PANELS_TO_RUN) + 1))
    for cfg in pivot.index:
        if cfg == "baseline":
            continue
        row = [cfg]
        for col in PANELS_TO_RUN:
            d = pivot.loc[cfg, col] - base[col]
            sign = "+" if d >= 0 else ""
            row.append(f"{sign}{d:.4f}")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")

    md_path = os.path.join(OUT_DIR, "ablation.md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {md_path}")

    # Pretty-print summary to stdout
    print("\n--- pivot ---")
    print(pivot.to_string())
    print("\n--- best per panel ---")
    for p, b in best_per_panel.items():
        print(f"  {p:<8} -> {b['config']:<10} F1={b['f1']:.4f}")

    # Save best-per-panel as JSON for F3 to load
    best_path = os.path.join(OUT_DIR, "ablation_best_per_panel.json")
    with open(best_path, "w") as f:
        json.dump(best_per_panel, f, indent=2)
    print(f"\nwrote {best_path}")


if __name__ == "__main__":
    main()
